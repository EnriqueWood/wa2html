_MONTHS = {
    "en": ["January", "February", "March", "April", "May", "June", "July", "August",
           "September", "October", "November", "December"],
    "es": ["enero", "febrero", "marzo", "abril", "mayo", "junio", "julio", "agosto",
           "septiembre", "octubre", "noviembre", "diciembre"],
}
_WEEKDAYS = {
    "en": ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"],
    "es": ["lunes", "martes", "miércoles", "jueves", "viernes", "sábado", "domingo"],
}


def t(lang: str, key: str) -> str:
    return STRINGS.get(lang, STRINGS["en"]).get(key) or STRINGS["en"].get(key, key)


def format_day(lang: str, day: date) -> str:
    """Static date label; the page re-renders it with the browser's Intl API."""
    if lang == "es":
        text = f"{_WEEKDAYS['es'][day.weekday()]}, {day.day} de {_MONTHS['es'][day.month - 1]} de {day.year}"
        return text[0].upper() + text[1:]
    return f"{_WEEKDAYS['en'][day.weekday()]}, {day.day} {_MONTHS['en'][day.month - 1]} {day.year}"
